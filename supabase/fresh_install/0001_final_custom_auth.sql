-- FINAL V3 MODEL — custom application authentication (username + password)
-- This migration replaces the V2 Supabase-Auth-linked model.
-- IMPORTANT: it resets V2 business/test data. auth.users is not used and is not modified.

begin;

create extension if not exists pgcrypto;

-- Remove V2 functions.
drop function if exists public.confirm_participation_delta(uuid, integer, uuid, text);
drop function if exists public.heartbeat_observer(uuid, text);
drop function if exists public.confirm_party_result(uuid, integer, uuid);
drop function if exists public.request_result_correction(uuid, integer, text);
drop function if exists public.resolve_result_correction(uuid, boolean);
drop function if exists public.set_election_mode(text);
drop function if exists public.current_app_user_id();
drop function if exists public.is_regional_admin();

-- Remove previous business model. auth.users is intentionally untouched.
drop table if exists public.user_sessions cascade;
drop table if exists public.result_corrections cascade;
drop table if exists public.party_results cascade;
drop table if exists public.observer_presence cascade;
drop table if exists public.participation_events cascade;
drop table if exists public.participation_counters cascade;
drop table if exists public.audit_logs cascade;
drop table if exists public.users cascade;
drop table if exists public.regional_settings cascade;
drop table if exists public.app_settings cascade;
drop table if exists public.local_bureaus cascade;
drop table if exists public.regional_offices cascade;

-- Legacy V1 names, in case the database skipped V2 cleanup.
drop table if exists public.observer_assignments cascade;
drop table if exists public.profiles cascade;
drop table if exists public.polling_stations cascade;
drop table if exists public.polling_centers cascade;
drop table if exists public.constituencies cascade;
