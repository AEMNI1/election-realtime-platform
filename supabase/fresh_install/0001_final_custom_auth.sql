create type public.app_role as enum ('OBSERVER', 'REGIONAL_ADMIN');
create type public.result_status as enum ('CONFIRMED', 'CORRECTION_PENDING', 'CORRECTED');
create type public.election_mode as enum ('PREPARATION', 'VOTING', 'COUNTING', 'COMPLETED');

create table public.regional_offices (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  region_label text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.regional_settings (
  regional_office_id uuid primary key references public.regional_offices(id) on delete cascade,
  election_mode public.election_mode not null default 'PREPARATION',
  orange_minutes integer not null default 5 check (orange_minutes between 1 and 120),
  red_minutes integer not null default 15 check (red_minutes between 2 and 240),
  updated_at timestamptz not null default now(),
  constraint red_after_orange check (red_minutes > orange_minutes)
);

create table public.local_bureaus (
  id uuid primary key default gen_random_uuid(),
  regional_office_id uuid not null references public.regional_offices(id) on delete restrict,
  code text not null,
  name text not null,
  address text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (regional_office_id, code),
  unique (id, regional_office_id)
);
create index local_bureaus_office_idx on public.local_bureaus(regional_office_id, active, code);

-- Application users only. They are NOT PostgreSQL users and are NOT Supabase Auth users.
-- The password is stored only as a one-way bcrypt hash generated by the backend.
create table public.users (
  id uuid primary key default gen_random_uuid(),
  regional_office_id uuid not null references public.regional_offices(id) on delete restrict,
  username text not null,
  password_hash text not null,
  full_name text not null,
  email text,
  phone text,
  role public.app_role not null,
  local_bureau_id uuid,
  active boolean not null default true,
  must_change_password boolean not null default false,
  failed_login_count integer not null default 0 check (failed_login_count >= 0),
  locked_until timestamptz,
  last_login_at timestamptz,
  password_changed_at timestamptz,
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint username_format check (username ~ '^[A-Za-z0-9._-]{3,60}$'),
  constraint observer_requires_bureau check (
    (role = 'OBSERVER' and local_bureau_id is not null)
    or (role = 'REGIONAL_ADMIN' and local_bureau_id is null)
  ),
  constraint users_bureau_same_office_fk
    foreign key (local_bureau_id, regional_office_id)
    references public.local_bureaus(id, regional_office_id)
    on delete restrict
);
create unique index users_username_ci_uq on public.users(lower(username));
create index users_office_role_idx on public.users(regional_office_id, role, active);
create index users_local_bureau_idx on public.users(local_bureau_id);

-- Core business rule: at most one ACTIVE observer can be assigned to a local bureau.
create unique index one_active_observer_per_local_bureau
  on public.users(local_bureau_id)
  where role = 'OBSERVER' and active = true;

create table public.user_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  last_seen_at timestamptz not null default now(),
  user_agent text,
  created_at timestamptz not null default now()
);
create index user_sessions_user_active_idx on public.user_sessions(user_id, expires_at desc) where revoked_at is null;

create table public.participation_counters (
  local_bureau_id uuid primary key references public.local_bureaus(id) on delete cascade,
  current_count integer not null default 0 check (current_count >= 0),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.users(id) on delete set null
);

create table public.participation_events (
  id uuid primary key default gen_random_uuid(),
  operation_uuid uuid not null unique,
  local_bureau_id uuid not null references public.local_bureaus(id) on delete restrict,
  observer_id uuid not null references public.users(id) on delete restrict,
  previous_value integer not null check (previous_value >= 0),
  delta integer not null check (delta <> 0),
  new_value integer not null check (new_value >= 0),
  device_id text,
  created_at timestamptz not null default now(),
  server_timestamp timestamptz not null default clock_timestamp()
);
create index participation_events_bureau_created_idx on public.participation_events(local_bureau_id, created_at desc);
create index participation_events_observer_created_idx on public.participation_events(observer_id, created_at desc);

create table public.observer_presence (
  observer_id uuid primary key references public.users(id) on delete cascade,
  local_bureau_id uuid not null unique references public.local_bureaus(id) on delete cascade,
  last_seen_at timestamptz not null default now(),
  connection_status text not null default 'CONNECTED'
    check (connection_status in ('CONNECTED','OFFLINE','BACKGROUND')),
  updated_at timestamptz not null default now()
);
create index observer_presence_last_seen_idx on public.observer_presence(last_seen_at desc);

create table public.party_results (
  id uuid primary key default gen_random_uuid(),
  operation_uuid uuid not null unique,
  local_bureau_id uuid not null unique references public.local_bureaus(id) on delete restrict,
  observer_id uuid not null references public.users(id) on delete restrict,
  votes integer not null check (votes >= 0),
  status public.result_status not null default 'CONFIRMED',
  submitted_at timestamptz not null default now(),
  confirmed_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index party_results_status_idx on public.party_results(status);

create table public.result_corrections (
  id uuid primary key default gen_random_uuid(),
  result_id uuid not null references public.party_results(id) on delete restrict,
  old_value integer not null check (old_value >= 0),
  proposed_value integer not null check (proposed_value >= 0),
  reason text not null check (char_length(trim(reason)) between 3 and 1000),
  requested_by uuid not null references public.users(id) on delete restrict,
  validated_by uuid references public.users(id) on delete restrict,
  status text not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create unique index one_pending_correction_per_result
  on public.result_corrections(result_id)
  where status = 'PENDING';

create table public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  regional_office_id uuid not null references public.regional_offices(id) on delete restrict,
  user_id uuid references public.users(id) on delete set null,
  action text not null,
  entity_type text,
  entity_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index audit_logs_office_created_idx on public.audit_logs(regional_office_id, created_at desc);
create index audit_logs_user_created_idx on public.audit_logs(user_id, created_at desc);
create index audit_logs_action_created_idx on public.audit_logs(action, created_at desc);

